def test_cost_from_usage_and_fallback():
    cents, src = cost_cents_from_images_usage(None, fallback_cents=40)
    assert cents == 40 and src == "estimate"
    usage = SimpleNamespace(
        input_tokens_details=SimpleNamespace(text_tokens=1000, image_tokens=1000),
        output_tokens=1000,
    )
    cents, src = cost_cents_from_images_usage(usage, fallback_cents=40)
    assert src == "provider_usage"
    # 1000*(5+8+30)/1e6 dollars = 0.043 → 4 cents
    assert cents == 4


