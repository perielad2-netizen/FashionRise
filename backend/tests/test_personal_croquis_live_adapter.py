def test_synthetic_fixture_is_fully_clothed_rgba():
    png = load_synthetic_clothed_adult_model_png()
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    with Image.open(io.BytesIO(png)) as img:
        assert img.mode in ("RGBA", "RGB")
        assert img.size[0] >= 256
        assert img.size[1] > img.size[0]  # full-body portrait aspect
    # Regenerated bytes match procedural renderer (deterministic enough for smoke).
    assert len(render_synthetic_clothed_adult_model_png()) > 500


def test_adapter_complete_but_live_http_fail_closed(monkeypatch):
    _enable_adapter_gates(monkeypatch, live_http="false")
    adapter = OpenAICroquisImagesEditAdapter()
    assert adapter.incomplete is False
    source = load_synthetic_clothed_adult_model_png()
    report = adapter.preflight_report(source)
    assert report["model"] == "gpt-image-2.5-sunburst"
    assert report["size"] == "1024x1536"
    assert report["quality"] == "medium"
    assert report["background"] == "transparent"
    assert report["output_format"] == "png"
    assert report["n"] == 1
    assert report["design_plane"] == "768x1024"
    assert report["estimate_cents"] == 40
    assert report["max_exposure_cents"] == 80
    assert report["live_http_armed"] is False
    with pytest.raises(ProviderNotAvailableError, match="LIVE_HTTP"):
        adapter.generate_line_art(source)
    # Tripwire not hit — refuse before creating a live client.
    assert provider_network_tripwire_hits() == 0


