def test_mocked_http_edit_normalizes_to_768x1024(monkeypatch):
    _enable_adapter_gates(monkeypatch, live_http="false")
    captured: dict = {}
    raw_out = _provider_portrait_png()

    def on_edit(**kwargs):
        captured.update(kwargs)
        item = SimpleNamespace(
            b64_json=base64.b64encode(raw_out).decode("ascii"),
            url=None,
        )
        return SimpleNamespace(
            data=[item],
            id="img_test_1",
            usage=SimpleNamespace(
                input_tokens_details=SimpleNamespace(text_tokens=120, image_tokens=800),
                output_tokens=2000,
            ),
        )

    set_croquis_openai_client_override(_FakeClient(on_edit))
    adapter = OpenAICroquisImagesEditAdapter()
    result = adapter.generate_line_art(load_synthetic_clothed_adult_model_png())
    assert captured["background"] == "transparent"
    assert captured["n"] == 1
    assert captured["size"] == "1024x1536"
    assert captured["quality"] == "medium"
    with Image.open(io.BytesIO(result.png_bytes)) as img:
        assert img.size == (DESIGN_W, DESIGN_H)
        assert img.mode == "RGBA"
    assert result.usage_source == "provider_usage"
    assert result.actual_cost_cents >= 1
    assert result.estimated_cost_cents == 40
    assert result.geometry_profile == pcp.GEOMETRY_PROFILE_V1
    assert provider_network_tripwire_hits() == 0


