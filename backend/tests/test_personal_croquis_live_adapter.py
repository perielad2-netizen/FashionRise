def _enable_adapter_gates(monkeypatch, *, live_http: str = "false") -> None:
    get_settings.cache_clear()
    monkeypatch.setenv("MY_CROQUIS_AI_ENABLED", "true")
    monkeypatch.setenv("MY_CROQUIS_AI_SPEND_CEILING_USD", "1.00")
    monkeypatch.setenv("MY_CROQUIS_AI_MAX_USD_PER_RUN", "1.00")
    monkeypatch.setenv("MY_CROQUIS_AI_MAX_EXPOSURE_CENTS", "80")
    monkeypatch.setenv("MY_CROQUIS_AI_ESTIMATE_CENTS", "40")
    monkeypatch.setenv("MY_CROQUIS_AI_LIVE_HTTP", live_http)
    monkeypatch.setenv("MY_CROQUIS_AI_IMAGE_SIZE", "1024x1536")
    monkeypatch.setenv("MY_CROQUIS_AI_IMAGE_QUALITY", "medium")
    monkeypatch.setenv("OPENAI_IMAGE_MODEL", "gpt-image-2.5-sunburst")
    monkeypatch.setenv("OPENAI_API_KEY", "sk-test-not-real")
    get_settings.cache_clear()


def _provider_portrait_png() -> bytes:
    """Fake provider output at 1024×1536 RGBA with transparency."""
    img = Image.new("RGBA", (1024, 1536), (0, 0, 0, 0))
    from PIL import ImageDraw

    draw = ImageDraw.Draw(img)
    draw.rectangle([400, 200, 624, 1300], outline=(10, 10, 10, 255), width=4)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


class _FakeImages:
    def __init__(self, on_edit):
        self._on_edit = on_edit
        self.edit_calls: list[dict] = []

    def edit(self, **kwargs):
        self.edit_calls.append(kwargs)
        return self._on_edit(**kwargs)


class _FakeClient:
    def __init__(self, on_edit):
        self.images = _FakeImages(on_edit)
        self.option_calls: list[dict] = []

    def with_options(self, **kwargs):
        self.option_calls.append(kwargs)
        return self


