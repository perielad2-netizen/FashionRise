#!/usr/bin/env bash
# Pick a 13-inch iPad, boot/install/launch FashionRise, install hardwired
# VNC helpers (fr-ipad-shot / fr-ipad-finish), then hold until finish signal
# or bounded timeout. Exits 0 so Codemagic publishes screenshot artifacts.
#
# Env:
#   FR_IPAD_SCREENSHOT_HOLD_MINUTES  — default 45 (fallback if finish not used)
#   BUNDLE_ID                        — default app.fashionrise.studio
#   FR_SIMULATOR_APP_PATH            — path to App.app (required)
set -euo pipefail

HOLD_MINUTES="${FR_IPAD_SCREENSHOT_HOLD_MINUTES:-45}"
BUNDLE_ID="${BUNDLE_ID:-app.fashionrise.studio}"
APP_PATH="${FR_SIMULATOR_APP_PATH:-}"
ROOT="${CM_BUILD_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
SHOT_DIR="${FR_IPAD_SCREENSHOT_DIR:-$ROOT/artifacts/ipad-screenshots}"
EXPORT_DIR="${CM_EXPORT_DIR:+$CM_EXPORT_DIR/ipad-screenshots}"
SESSION_DIR="$ROOT/artifacts/ipad-session"
FINISH_FLAG="$SESSION_DIR/FINISH.flag"
HELPER_SRC="$ROOT/scripts/codemagic-ipad-screenshot.sh"
PICK_SRC="$ROOT/scripts/codemagic-pick-ipad-simulator.sh"
BIN_DIR="$HOME/bin"
DESKTOP="${HOME}/Desktop"

if [[ -z "$APP_PATH" || ! -d "$APP_PATH" ]]; then
  echo "codemagic-ipad-screenshots-session: FAIL — set FR_SIMULATOR_APP_PATH to App.app" >&2
  exit 1
fi
if [[ ! -f "$HELPER_SRC" || ! -f "$PICK_SRC" ]]; then
  echo "codemagic-ipad-screenshots-session: FAIL — helper scripts missing under $ROOT/scripts" >&2
  exit 1
fi

chmod +x "$HELPER_SRC" "$PICK_SRC"
mkdir -p "$SHOT_DIR" "$SESSION_DIR" "$BIN_DIR" "$DESKTOP"
if [[ -n "$EXPORT_DIR" ]]; then
  mkdir -p "$EXPORT_DIR"
fi
rm -f "$FINISH_FLAG"

echo "=== Selecting 13-inch iPad simulator ==="
PICK="$("$PICK_SRC")"
UDID="${PICK%%|*}"
REST="${PICK#*|}"
SIM_NAME="${REST%%|*}"
RUNTIME="${REST##*|}"
echo "Using UDID=$UDID name=$SIM_NAME"

# Persist session config for debugging / tests (no secrets).
cat > "$SESSION_DIR/session.env" <<EOF
FR_IPAD_UDID=$UDID
FR_IPAD_NAME=$SIM_NAME
FR_IPAD_RUNTIME=$RUNTIME
FR_IPAD_SCREENSHOT_DIR=$SHOT_DIR
FR_IPAD_EXPORT_DIR=${EXPORT_DIR:-}
FR_IPAD_FINISH_FLAG=$FINISH_FLAG
FR_IPAD_BUNDLE_ID=$BUNDLE_ID
EOF

# --- Generated wrappers: hardwired UDID + dirs so a fresh VNC Terminal works ---
write_shot_wrapper() {
  local dest="$1"
  if [[ -n "${EXPORT_DIR:-}" ]]; then
    cat > "$dest" <<EOF
#!/usr/bin/env bash
# Generated by FashionRise iPad screenshot session — hardwired paths/UDID.
set -euo pipefail
exec "$HELPER_SRC" --udid "$UDID" --out "$SHOT_DIR" --export "$EXPORT_DIR" "\$@"
EOF
  else
    cat > "$dest" <<EOF
#!/usr/bin/env bash
# Generated by FashionRise iPad screenshot session — hardwired paths/UDID.
set -euo pipefail
exec "$HELPER_SRC" --udid "$UDID" --out "$SHOT_DIR" "\$@"
EOF
  fi
  chmod +x "$dest"
}

write_finish_wrapper() {
  local dest="$1"
  cat > "$dest" <<EOF
#!/usr/bin/env bash
# Signal the Codemagic screenshot session to finish successfully.
set -euo pipefail
FLAG="$FINISH_FLAG"
mkdir -p "$(dirname "$FINISH_FLAG")"
date -u +%Y-%m-%dT%H:%M:%SZ > "\$FLAG"
echo "fr-ipad-finish: signaled session complete (\$FLAG)"
echo "Leave this window open — Codemagic will collect screenshots and publish Artifacts."
EOF
  chmod +x "$dest"
}

write_shot_wrapper "$BIN_DIR/fr-ipad-shot"
write_finish_wrapper "$BIN_DIR/fr-ipad-finish"
write_shot_wrapper "$DESKTOP/fr-ipad-shot"
write_finish_wrapper "$DESKTOP/fr-ipad-finish"
write_shot_wrapper "$SESSION_DIR/fr-ipad-shot"
write_finish_wrapper "$SESSION_DIR/fr-ipad-finish"

# Ensure new Terminal windows see ~/bin (VNC often starts a login shell).
for rc in "$HOME/.zprofile" "$HOME/.zshrc" "$HOME/.bash_profile" "$HOME/.bashrc"; do
  touch "$rc"
  if ! grep -q 'FashionRise iPad screenshot PATH' "$rc" 2>/dev/null; then
    cat >> "$rc" <<'EOF'

# FashionRise iPad screenshot PATH (Codemagic VNC)
export PATH="$HOME/bin:$PATH"
EOF
  fi
done

ABS_SHOT="$BIN_DIR/fr-ipad-shot"
ABS_FINISH="$BIN_DIR/fr-ipad-finish"

cat > "$DESKTOP/FashionRise-iPad-Screenshots-README.txt" <<EOF
FashionRise — iPad screenshot session (Codemagic remote Mac)

Simulator UDID (hardwired into helpers): $UDID
Device: $SIM_NAME

1. Simulator should already show FashionRise.
2. Sign in (do not paste secrets into Codemagic logs).
3. Navigate to each App Store screenshot screen.
4. Capture (any of these work in a fresh Terminal):
     fr-ipad-shot
     fr-ipad-shot studio-home
     $ABS_SHOT
     $DESKTOP/fr-ipad-shot
5. When done, finish successfully (do NOT cancel the Codemagic build):
     fr-ipad-finish
     $ABS_FINISH
6. Wait for the build to go green, then download Artifacts → ipad-screenshots/

Output directory (hardwired):
  $SHOT_DIR
EOF

# Double-clickable .command launchers for VNC (open Terminal and run).
cat > "$DESKTOP/Capture-Screenshot.command" <<EOF
#!/bin/bash
export PATH="\$HOME/bin:\$PATH"
"$ABS_SHOT"
read -r -p "Press Enter to close…"
EOF
chmod +x "$DESKTOP/Capture-Screenshot.command"

cat > "$DESKTOP/Finish-Screenshot-Session.command" <<EOF
#!/bin/bash
export PATH="\$HOME/bin:\$PATH"
"$ABS_FINISH"
read -r -p "Press Enter to close…"
EOF
chmod +x "$DESKTOP/Finish-Screenshot-Session.command"

echo "=== Booting Simulator GUI ==="
open -a Simulator --args -CurrentDeviceUDID "$UDID" || open -a Simulator
xcrun simctl boot "$UDID" 2>/dev/null || true
for _ in $(seq 1 60); do
  if xcrun simctl list devices | grep "$UDID" | grep -q Booted; then
    break
  fi
  sleep 2
done
xcrun simctl bootstatus "$UDID" -b || true
if ! xcrun simctl list devices | grep "$UDID" | grep -q Booted; then
  echo "codemagic-ipad-screenshots-session: FAIL — could not boot $UDID" >&2
  exit 1
fi

echo "=== Installing FashionRise (.app) ==="
xcrun simctl uninstall "$UDID" "$BUNDLE_ID" 2>/dev/null || true
xcrun simctl install "$UDID" "$APP_PATH"
xcrun simctl launch "$UDID" "$BUNDLE_ID"

echo "=== Boot smoke screenshot (must succeed) ==="
# Fail loud — do not continue a broken capture path into the VNC hold.
"$ABS_SHOT" boot-smoke

cat <<EOF

============================================================
FashionRise iPad Screenshots — VNC hold (up to ${HOLD_MINUTES} min)
============================================================
1) Codemagic build page → Explore build machine via VNC
2) Windows: RealVNC Viewer → HOST:PORT + one-time credentials
3) Capture:
      fr-ipad-shot
      $ABS_SHOT my-label
4) Finish successfully (preferred — publishes Artifacts):
      fr-ipad-finish
5) Wait for the build to succeed, then download ipad-screenshots/

Do NOT cancel a successful session — use fr-ipad-finish.
Fallback: hold ends after ${HOLD_MINUTES} minutes and still publishes.
No IPA publish · no ASC · no IAP gate changes.
============================================================

EOF

HOLD_SECONDS=$((HOLD_MINUTES * 60))
echo "Holding up to ${HOLD_MINUTES} minutes — waiting for fr-ipad-finish (or timeout)..."
deadline=$((SECONDS + HOLD_SECONDS))
finished=0
while (( SECONDS < deadline )); do
  if [[ -f "$FINISH_FLAG" ]]; then
    echo "Finish signal received at $(cat "$FINISH_FLAG")"
    finished=1
    break
  fi
  sleep 2
done

if [[ "$finished" -eq 0 ]]; then
  echo "Hold timeout reached — collecting screenshots and finishing successfully."
fi

echo "=== Collecting screenshot artifacts ==="
count="$(find "$SHOT_DIR" -maxdepth 1 -type f -name 'shot-*.png' 2>/dev/null | wc -l | tr -d ' ')"
if [[ "$count" -lt 1 ]]; then
  echo "codemagic-ipad-screenshots-session: FAIL — no screenshots in $SHOT_DIR" >&2
  exit 1
fi
if [[ -n "$EXPORT_DIR" ]]; then
  mkdir -p "$EXPORT_DIR"
  cp -f "$SHOT_DIR"/shot-*.png "$EXPORT_DIR/" 2>/dev/null || true
fi
ls -la "$SHOT_DIR"
echo "codemagic-ipad-screenshots-session: ok shots=$count finish_signaled=$finished"
# Exit 0 so Codemagic marks the build successful and publishes Artifacts.
exit 0
